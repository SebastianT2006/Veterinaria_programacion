using front_veterinaria.Seguridad;
using presentaciones_veterinaria.implementaciones;
using presentaciones_veterinaria.interfaces;
var builder = WebApplication.CreateBuilder(args);
// FiltroSesion revisa en cada pagina que haya un usuario en la sesion
builder.Services.AddRazorPages(opciones => opciones.Conventions.ConfigureFilter(new FiltroSesion()));
builder.Services.AddDistributedMemoryCache();
builder.Services.AddSession(opciones => opciones.IdleTimeout = TimeSpan.FromMinutes(30));
builder.Services.AddHttpContextAccessor();
builder.Services.AddControllers();
builder.Services.AddScoped<IComunicaciones, Comunicaciones>();
builder.Services.AddScoped<IanimalesPresentacion, animalesPresentacion>();
builder.Services.AddScoped<IcitasPresentacion, citasPresentacion>();
builder.Services.AddScoped<IclientesPresentacion, clientesPresentacion>();
builder.Services.AddScoped<IcomprasPresentacion, comprasPresentacion>();
builder.Services.AddScoped<IconsultasPresentacion, consultasPresentacion>();
builder.Services.AddScoped<IdetalleComprasPresentacion, detalleComprasPresentacion>();
builder.Services.AddScoped<IdetalleFacturasPresentacion, detalleFacturasPresentacion>();
builder.Services.AddScoped<IempleadosPresentacion, empleadosPresentacion>();
builder.Services.AddScoped<IespeciesPresentacion, especiesPresentacion>();
builder.Services.AddScoped<IfacturasPresentacion, facturasPresentacion>();
builder.Services.AddScoped<IfincasPresentacion, fincasPresentacion>();
builder.Services.AddScoped<IhistoriasClinicasPresentacion, historiasClinicasPresentacion>();
builder.Services.AddScoped<IpersonasPresentacion, personasPresentacion>();
builder.Services.AddScoped<IproductosPresentacion, productosPresentacion>();
builder.Services.AddScoped<IproveedoresPresentacion, proveedoresPresentacion>();
builder.Services.AddScoped<IrazasPresentacion, razasPresentacion>();
builder.Services.AddScoped<IserviciosPresentacion, serviciosPresentacion>();
builder.Services.AddScoped<ItratamientosPresentacion, tratamientosPresentacion>();
builder.Services.AddScoped<IvacunacionesPresentacion, vacunacionesPresentacion>();
builder.Services.AddScoped<IveterinariosPresentacion, veterinariosPresentacion>();
builder.Services.AddScoped<IrolesPresentacion, rolesPresentacion>();
builder.Services.AddScoped<IusuariosPresentacion, usuariosPresentacion>();
builder.Services.AddScoped<IauditoriasPresentacion, auditoriasPresentacion>();
var app = builder.Build();
if (!app.Environment.IsDevelopment()) { app.UseExceptionHandler("/Error"); app.UseHsts(); }
app.UseHttpsRedirection();
app.UseRouting();
app.UseSession();
app.UseAuthorization();
app.MapStaticAssets();
app.MapRazorPages().WithStaticAssets();
app.Run();
